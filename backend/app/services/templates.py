# 카드 기본값(집필카드의 빈 형태)
_CARD0 = {"purpose": "", "question": "", "message": "", "content": "", "length": "1쪽", "status": "작성 전"}


def _n(title, children=None, **card):
    """목차 항목 하나. card 키워드는 집필카드를 미리 채운다(없으면 빈 카드)."""
    node = {"title": title, "children": children or []}
    if card:
        c = dict(_CARD0)
        c.update({k: v for k, v in card.items() if v is not None})
        node["card"] = c
    return node


def _t(*titles):
    """카드 없는 단순 항목들."""
    return [_n(t) if isinstance(t, str) else t for t in titles]


